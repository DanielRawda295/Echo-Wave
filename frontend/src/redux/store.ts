// src/redux/store.ts

/**
 * Redux Store Configuration
 * 
 * This file configures the central Redux store for the application's state management.
 * It combines all reducers and middleware to create a single source of truth for the app state.
 * 
 * The store manages:
 * - Music API data and caching (via RTK Query)
 * - Music player state and controls
 * - Future state slices can be easily added here
 * 
 * @module store
 */

import { configureStore } from '@reduxjs/toolkit';
import { musicApi } from './services/MusicApi';
import playerReducer from '../redux/features/playerSlice';

/**
 * Redux Store Instance
 * 
 * The central store that holds the complete state tree of the application.
 * Uses Redux Toolkit's configureStore for simplified setup with good defaults.
 * 
 * @constant {Object} store - Configured Redux store instance
 * 
 * Store Configuration:
 * - Combines multiple reducers into a single state tree
 * - Applies necessary middleware for async operations
 * - Includes Redux DevTools extension support
 * - Uses immutable state updates with Immer internally
 */
export const store = configureStore({
  /**
   * Root Reducer Configuration
   * 
   * Defines the structure of the Redux state tree by combining all reducers.
   * Each property represents a slice of the global state.
   */
  reducer: {
    /**
     * Music API Slice
     * 
     * Managed by RTK Query, this slice handles:
     * - API data caching and normalization
     * - Loading states for all music requests
     * - Error states for failed API calls
     * - Automatic cache invalidation and refetching
     * 
     * The reducerPath is dynamically generated by RTK Query
     */
    [musicApi.reducerPath]: musicApi.reducer,

    /**
     * Player Slice
     * 
     * Manages music playback state including:
     * - Current playing song and queue
     * - Play/pause state
     * - Song navigation (next/previous)
     * - Genre selection for discovery
     * - Player active/inactive status
     */
    player: playerReducer,
    
    /**
     * Future Reducers Can Be Added Here:
     * 
     * @example
     * user: userReducer,        // User profile and preferences
     * theme: themeReducer,      // UI theme settings
     * favorites: favoritesReducer, // User's favorite songs
     * playlists: playlistsReducer, // User-created playlists
     */
  },

  /**
   * Middleware Configuration
   * 
   * Extends the default middleware with RTK Query's custom middleware
   * for handling API caching, invalidation, and other advanced features.
   * 
   * Default middleware includes:
   * - Redux Thunk (async action support)
   * - Immutable State Invariant (development)
   * - Serializability Check (development)
   * 
   * @param {Function} getDefaultMiddleware - Function that returns default middleware array
   * @returns {Array} Enhanced middleware array with RTK Query middleware
   */
  middleware: (getDefaultMiddleware) =>
    getDefaultMiddleware()
      // Add RTK Query middleware for API caching and lifecycle
      .concat(musicApi.middleware),
});

/**
 * RootState Type
 * 
 * Inferring the RootState type from the store itself provides perfect type safety.
 * This type represents the complete shape of the Redux state tree.
 * 
 * @typedef {ReturnType<typeof store.getState>} RootState
 * 
 * Usage in components with useSelector:
 * @example
 * const currentSong = useSelector((state: RootState) => state.player.activeSong);
 * const searchResults = useSelector((state: RootState) => state.musicApi.queries['searchSongs("rock")']?.data);
 */
export type RootState = ReturnType<typeof store.getState>;

/**
 * AppDispatch Type
 * 
 * Inferring the dispatch type from the store ensures type-safe action dispatching.
 * This type knows about all the possible actions that can be dispatched.
 * 
 * @typedef {typeof store.dispatch} AppDispatch
 * 
 * Usage with useDispatch hook:
 * @example
 * const dispatch = useDispatch<AppDispatch>();
 * dispatch(playPause(true));
 * dispatch(musicApi.endpoints.getTopCharts.initiate());
 */
export type AppDispatch = typeof store.dispatch;

/**
 * Store Architecture Benefits:
 * 
 * 1. **Single Source of Truth**: All application state in one predictable container
 * 2. **Predictable State Updates**: State can only be updated through defined actions
 * 3. **Centralized State Management**: Easy to debug and monitor state changes
 * 4. **Type Safety**: Full TypeScript support with inferred types
 * 5. **DevTools Integration**: Redux DevTools for time-travel debugging
 * 6. **Middleware Support**: Easy to add logging, analytics, or other side effects
 * 
 * @example
 * // Accessing store in non-React contexts
 * import { store } from './redux/store';
 * 
 * // Get current state
 * const currentState = store.getState();
 * 
 * // Dispatch actions
 * store.dispatch(playPause(true));
 * 
 * // Subscribe to state changes
 * const unsubscribe = store.subscribe(() => {
 *   console.log('State updated:', store.getState());
 * });
 */

/**
 * Integration with React Application:
 * 
 * The store is provided to the React application through the Provider component
 * in main.tsx, making the Redux state available to all components in the tree.
 * 
 * @example
 * // In main.tsx
 * import { Provider } from 'react-redux';
 * import { store } from './redux/store';
 * 
 * ReactDOM.render(
 *   <Provider store={store}>
 *     <App />
 *   </Provider>,
 *   document.getElementById('root')
 * );
 */